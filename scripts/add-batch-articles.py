#!/usr/bin/env python3
"""Genere un lot de nouveaux articles MDX pour vacances-bons-plans.fr

Usage : python3 scripts/add-batch-articles.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
PARTNER_TAG = "lebrunnathali-21"
TODAY = "2026-07-29"


def amazon_search(query):
    q = query.replace(" ", "+")
    return f"https://www.amazon.fr/s?k={q}&tag={PARTNER_TAG}"


def render_products_section(products):
    """products : liste de dict {name, search, price, points, cta}"""
    out = ["## Notre selection"]
    for i, p in enumerate(products, 1):
        out.append(f"\n### {i}. {p['name']}\n")
        out.append(p["desc"])
        out.append("\n**Points forts :**")
        for pt in p["points"]:
            out.append(f"- {pt}")
        out.append(f"\n**Prix moyen :** {p['price']}\n")
        out.append(f"[{p['cta']}]({amazon_search(p['search'])})")
        out.append("\n---")
    return "\n".join(out)


def render_table(headers, rows):
    out = ["\n## Tableau comparatif\n"]
    out.append("| " + " | ".join(headers) + " |")
    out.append("|" + "|".join("---" for _ in headers) + "|")
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    return "\n".join(out) + "\n"


def render_article(a):
    tags_yaml = ", ".join(f'"{t}"' for t in a["tags"])
    frontmatter = f"""---
title: "{a['title']}"
description: "{a['description']}"
date: "{a.get('date', TODAY)}"
category: "{a['category']}"
tags: [{tags_yaml}]
image: "/images/articles/{a['slug']}.svg"
imageAlt: "{a['imageAlt']}"
published: true
featured: false
seoTitle: "{a['seoTitle']}"
seoDescription: "{a['seoDescription']}"
---
"""
    body_parts = ["", a["intro"], ""]
    for title, paras in a["sections"]:
        body_parts.append(f"## {title}\n")
        for p in paras:
            body_parts.append(p)
            body_parts.append("")
    if a.get("products"):
        body_parts.append(render_products_section(a["products"]))
    if a.get("table_headers"):
        body_parts.append(render_table(a["table_headers"], a["table_rows"]))
    if a.get("conclusion"):
        body_parts.append(f"\n## Notre conseil\n\n{a['conclusion']}")
    if a.get("final_cta"):
        body_parts.append(f"\n[{a['final_cta_label']}]({amazon_search(a['final_cta'])})")
    return frontmatter + "\n".join(body_parts) + "\n"


def main():
    existing = {f.stem for f in CONTENT.glob("*.mdx")}
    added = 0
    skipped = []
    for a in ARTICLES:
        if a["slug"] in existing:
            skipped.append(a["slug"])
            continue
        (CONTENT / f"{a['slug']}.mdx").write_text(render_article(a), encoding="utf-8")
        print(f"[+] {a['slug']}.mdx")
        added += 1
    if skipped:
        print(f"\n[skip] deja presents : {', '.join(skipped)}")
    print(f"\nOK : {added} articles ajoutes.")


