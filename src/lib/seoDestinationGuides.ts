function renderGuideContent(guide: SeoDestinationGuide) {
  const areas = guide.areas
    .map((area, index) => `### ${index + 1}. ${area.name}\n\n**Idéal pour :** ${area.bestFor}. ${area.note}.`)
    .join("\n\n");
  const activities = guide.activities.map((item) => `- ${item}`).join("\n");
  const watchouts = guide.watchouts.map((item) => `- ${item}`).join("\n");

  return `${guide.intro}\n\n## À qui convient cette destination ?\n\n${guide.profile}\n\n## Les secteurs à comparer\n\n${areas}\n\n## Quel budget prévoir pour un mobil-home ?\n\nLes montants ci-dessous sont des **fourchettes indicatives pour une semaine et non des prix en temps réel**. Ils varient selon la capacité, le classement, les options et la date de réservation.\n\n| Période | Budget indicatif |\n|---|---:|\n| Mai à juin | ${guide.budget[0]} |\n| Juillet à août | ${guide.budget[1]} |\n| Septembre | ${guide.budget[2]} |\n\nAvant de comparer, additionnez le ménage, le linge, la taxe de séjour, les frais de dossier et les éventuels suppléments pour le véhicule ou la climatisation.\n\n## Quand partir ?\n\n${guide.seasons}\n\n## Que faire pendant le séjour ?\n\n${activities}\n\n## Les points à vérifier avant de réserver\n\n${watchouts}\n\n## Notre conseil\n\n${guide.verdict}\n\nLes disponibilités et tarifs changent rapidement : indiquez vos vraies dates et le nombre de voyageurs chez le partenaire pour obtenir le prix total à jour.`;
}

export function getSeoDestinationArticles() {
  return seoDestinationGuides.map((guide) => ({
    slug: guide.slug,
    title: guide.title,
    description: guide.description,
    date: "2026-09-06",
    category: "destination",
    tags: guide.tags,
    image: "",
    imageAlt: `Vacances en camping à ${guide.title.replace(/^Camping (à|au|dans|sur|près du) /, "").replace(/ :.*$/, "")}`,
    published: true,
    featured: false,
    seoTitle: guide.seoTitle,
    seoDescription: guide.seoDescription,
    content: renderGuideContent(guide),
  }));
}
